/** The country a state, province, Mexican state or Taiwanese county belongs to. */
export function countryOfJuris(code) {
  if (code === 'HK') return 'hk';
  if (Object.hasOwn(EA_LABEL, code)) return 'tw';
  return isProvince(code) ? 'ca' : isMxState(code) ? 'mx' : 'us';
}

const labelPair = (code) => STATE_LABEL[code] || PROVINCE_LABEL[code] || MX_STATE_LABEL[code] || EA_LABEL[code];

/**
 * Both names for a jurisdiction, for the search haystack.
 *
 * The haystack is built once when the index loads, so it cannot depend on the
 * current language or switching languages would break search. Carrying both
 * names costs nothing and means "ontario" and "安大略" both work either way.
 */
export function jurisdictionNames(code) {
  const pair = labelPair(code);
  return pair ? `${pair[0]} ${pair[1]}` : code;
}

let lang = 'en';

export function setLang(next) {
  lang = STRINGS[next] ? next : 'en';
  document.documentElement.lang = lang === 'zh' ? 'zh-Hans' : 'en';
  document.documentElement.dataset.lang = lang;
  return lang;
}

export function getLang() { return lang; }

export function t(key, vars) {
  const table = STRINGS[lang] || STRINGS.en;
  let s = table[key] ?? STRINGS.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
  return s;
}

/** The name of a state, province or territory, in the current language. */
export function stateName(code) {
  const pair = labelPair(code);
  if (!pair) return code;
  return lang === 'zh' ? pair[1] : pair[0];
}

/**
 * What to call the body a route belongs to.
 *
 * For the two numbered-by-jurisdiction tiers the useful name is the state or
 * province, because "State Routes" says nothing about which one. For the
 * national systems it is the system itself. This is the line under every
 * search result, palette hit and table row, so it lives in one place.
 */
/**
 * What to name a route by, beside its number.
 *
 * Per-jurisdiction systems obviously want their jurisdiction. So do Canada's
 * two national tiers, which is less obvious: the Trans-Canada is a designation
 * carried by provincial highways and it changes number at nearly every border,
 * so five separate roads are all signed "TCH 1" and only the province tells
 * them apart. An American national route needs none of this, because its
 * number is unique and its name already says which system it belongs to.
 */
export function ownerLabel(sys, code) {
  if (isPerJuris(sys) || isProvince(code)) return stateName(code);
  return t(`sys.${sys}`);
}

/* Units are the reader's choice, not the source's. Lengths are held in
   whatever unit the figure was measured or published in - miles for the
   route index and American registers, kilometres for Canadian and Mexican
   inventories - and converted only here, at the point of display, so the
   switch changes what is read and never what is kept. */
let units = 'imperial';

export function setUnits(next) {
  units = next === 'metric' ? 'metric' : 'imperial';
  document.documentElement.dataset.units = units;
  return units;
}

export function getUnits() { return units; }

/** The three countries that still drive in miles; everyone else opens in km. */
export function defaultUnits(locale = navigator.language || '') {
  const region = (locale.split('-')[1] || '').toUpperCase();
  return ['US', 'LR', 'MM'].includes(region) ? 'imperial' : 'metric';
}

const isMetric = () => units === 'metric';

/** A length held in miles, in the reader's unit. */
export function lenOf(mi) { return mi == null ? null : isMetric() ? mi * KM_PER_MI : mi; }
/** A length held in kilometres, in the reader's unit. */
export function lenOfKm(km) { return km == null ? null : isMetric() ? km : km / KM_PER_MI; }
export function lenUnit() { return t(isMetric() ? 'unit.km' : 'unit.mi'); }
/** "Miles" or "Kilometres", for column heads. */
export function lenName() { return t(isMetric() ? 'unit.long.km' : 'unit.long.mi'); }

export function dist(mi, digits = 0) {
  return mi == null ? '—' : `${num(lenOf(mi), digits)} ${lenUnit()}`;
}
// A route's length is held to the whole mile, so a road under half a mile is
// 0 there. It reads "<1" rather than as a road of no length.
export function lenNum(mi) { return mi === 0 ? '<1' : num(lenOf(mi)); }
export function routeDist(mi) { return mi === 0 ? `<1 ${lenUnit()}` : dist(mi); }

export function distKm(km, digits = 0) {
  return km == null ? '—' : `${num(lenOfKm(km), digits)} ${lenUnit()}`;
}

/** The other unit, for the line under a headline length. */
export function distAlt(mi) {
  if (mi == null) return '—';
  if (mi === 0) return `<1 ${t(isMetric() ? 'unit.mi' : 'unit.km')}`;
  return isMetric() ? `${num(mi)} ${t('unit.mi')}` : `${num(mi * KM_PER_MI)} ${t('unit.km')}`;
}

export function speedKph(kph) {
  if (kph == null) return '—';
  return isMetric() ? `${num(kph)} ${t('unit.kph')}` : `${num(kph / KM_PER_MI)} ${t('unit.mph')}`;
}
export function speedMph(mph) {
  if (mph == null) return '—';
  return isMetric() ? `${num(mph * KM_PER_MI)} ${t('unit.kph')}` : `${num(mph)} ${t('unit.mph')}`;
}

export function heightFt(ft) {
  if (ft == null) return '—';
  return isMetric() ? `${num(ft * 0.3048)} ${t('unit.m')}` : `${num(ft)} ${t('unit.ft')}`;
}

/**
 * A route's display label.
 *
 * Labels are built once, at build time, and are almost language-independent:
 * "I-95", "US 66", "ON 401" and "A-20" read the same either way, because the
 * number and the jurisdiction code are what is on the sign. The Trans-Canada
 * is the exception - it is a name rather than a code - so it translates.
 */
export function routeLabel(label) {
  if (lang === 'zh') return zhLabel(label) ?? label ?? '';
  return label ?? '';
}

// Taiwan's suffixes are the celestial stems, 甲 to 庚, which the English
// labels carry as A to G. Hong Kong's routes are 幹線 on their own signs.
const STEM = { A: '甲', B: '乙', C: '丙', D: '丁', E: '戊', F: '己', G: '庚' };
const EA_ZH = [
  [/^Fwy (\d+)([A-G]?)$/, (n, s) => `國${n}${STEM[s] ?? ''}`],
  [/^PH (\d+)([A-G]?)$/, (n, s) => `台${n}${STEM[s] ?? ''}`],
  [/^Route (\d+)$/, (n) => `${n}號幹線`],
];

function zhLabel(label) {
  if (!label) return null;
  if (label.startsWith('TCH ')) return `横加公路 ${label.slice(4)}`;
  for (const [re, fn] of EA_ZH) {
    const m = re.exec(label);
    if (m) return fn(m[1], m[2]);
  }
  return null;
}

/** A label's Chinese form where it has one, for the search haystack. */
export function labelAlias(label) { return zhLabel(label) ?? ''; }

export function num(n, digits = 0) {
  if (n == null || Number.isNaN(n)) return '—';
  return n.toLocaleString(lang === 'zh' ? 'zh-CN' : 'en-US', {
    minimumFractionDigits: digits, maximumFractionDigits: digits,
  });
}
